-- Arana Space operational features: order workflow, payments, cashier shifts and realtime.
-- Additive migration: existing menu, orders, customers and table QR records are preserved.

alter table public.orders
  add column if not exists payment_method text,
  add column if not exists paid_at timestamptz,
  add column if not exists paid_by uuid references auth.users(id) on delete set null,
  add column if not exists ready_at timestamptz;

alter table public.orders drop constraint if exists orders_order_type_check;
alter table public.orders add constraint orders_order_type_check
  check (order_type = any (array['preorder','dine_in','takeaway']));
alter table public.orders add constraint orders_payment_method_check
  check (payment_method is null or payment_method = any (array['cash','qris']));

drop policy if exists "staff read cafe tables" on public.cafe_tables;
create policy "staff read cafe tables" on public.cafe_tables
for select to authenticated
using (exists (
  select 1 from public.profiles p
  where p.id=(select auth.uid()) and p.role in ('admin','cashier','kitchen')
));

create table if not exists public.cashier_shifts (
  id bigint generated by default as identity primary key,
  cashier_id uuid not null references auth.users(id) on delete restrict,
  opening_cash numeric(12,2) not null default 0 check (opening_cash >= 0),
  closing_cash numeric(12,2) check (closing_cash is null or closing_cash >= 0),
  expected_cash numeric(12,2),
  cash_difference numeric(12,2),
  status text not null default 'open' check (status in ('open','closed')),
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  created_at timestamptz not null default now()
);
create unique index if not exists cashier_shifts_one_open_per_user
  on public.cashier_shifts(cashier_id) where status='open';
alter table public.cashier_shifts enable row level security;
grant select, insert, update on public.cashier_shifts to authenticated;

drop policy if exists "staff read cashier shifts" on public.cashier_shifts;
create policy "staff read cashier shifts" on public.cashier_shifts
for select to authenticated
using (cashier_id=(select auth.uid()) or exists (
  select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='admin'
));
drop policy if exists "cashier open own shift" on public.cashier_shifts;
create policy "cashier open own shift" on public.cashier_shifts
for insert to authenticated
with check (cashier_id=(select auth.uid()) and exists (
  select 1 from public.profiles p where p.id=(select auth.uid()) and p.role in ('admin','cashier')
));
drop policy if exists "cashier close own shift" on public.cashier_shifts;
create policy "cashier close own shift" on public.cashier_shifts
for update to authenticated
using (cashier_id=(select auth.uid()) or exists (
  select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='admin'
))
with check (cashier_id=(select auth.uid()) or exists (
  select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='admin'
));

create or replace function public.create_customer_order_v2(
  p_customer_name text,
  p_customer_phone text,
  p_customer_note text default null,
  p_pickup_at timestamptz default null,
  p_items jsonb default '[]'::jsonb,
  p_order_type text default 'takeaway',
  p_table_id bigint default null,
  p_payment_method text default 'cash'
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare
  v_result jsonb;
  v_number text;
  v_method text:=lower(coalesce(p_payment_method,'cash'));
  v_type text:=lower(coalesce(p_order_type,'takeaway'));
begin
  if v_method not in ('cash','qris') then raise exception 'Metode pembayaran tidak valid'; end if;
  if v_type not in ('dine_in','takeaway') then raise exception 'Jenis pesanan tidak valid'; end if;
  if v_type='dine_in' and p_table_id is null then raise exception 'Pilih meja melalui QR meja'; end if;
  v_result:=public.create_customer_order(
    p_customer_name,p_customer_phone,p_customer_note,p_pickup_at,p_items,
    case when v_type='takeaway' then 'preorder' else 'dine_in' end,p_table_id
  );
  v_number:=v_result->>'order_number';
  perform set_config('app.order_creation','create',true);
  update public.orders set order_type=v_type,payment_method=v_method,
    payment_status=case when v_method='qris' then 'pending' else 'unpaid' end
    where order_number=v_number;
  perform set_config('app.order_creation','',true);
  return v_result || jsonb_build_object(
    'payment_method',v_method,
    'payment_status',case when v_method='qris' then 'pending' else 'unpaid' end,
    'order_type',v_type
  );
end $$;
revoke all on function public.create_customer_order_v2(text,text,text,timestamptz,jsonb,text,bigint,text) from public;
grant execute on function public.create_customer_order_v2(text,text,text,timestamptz,jsonb,text,bigint,text) to anon, authenticated;

create or replace function public.lookup_customer_order(p_order_number text,p_customer_phone text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_order public.orders%rowtype; v_items jsonb;
begin
  if coalesce(trim(p_order_number),'')='' or coalesce(trim(p_customer_phone),'')='' then
    raise exception 'Nomor pesanan dan nomor WhatsApp wajib diisi';
  end if;
  select * into v_order from public.orders
  where order_number=upper(trim(p_order_number))
    and regexp_replace(coalesce(customer_phone,''),'[^0-9]','','g')
      = regexp_replace(trim(p_customer_phone),'[^0-9]','','g');
  if not found then raise exception 'Pesanan tidak ditemukan. Periksa nomor pesanan dan WhatsApp.'; end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'product_name',oi.product_name,'quantity',oi.quantity,'line_total',oi.line_total
  ) order by oi.id),'[]'::jsonb) into v_items
  from public.order_items oi where oi.order_id=v_order.id;
  return jsonb_build_object(
    'order_number',v_order.order_number,'order_status',v_order.order_status,
    'payment_status',v_order.payment_status,'payment_method',v_order.payment_method,
    'order_type',v_order.order_type,'grand_total',v_order.grand_total,
    'created_at',v_order.created_at,'ready_at',v_order.ready_at,'items',v_items
  );
end $$;
revoke all on function public.lookup_customer_order(text,text) from public;
grant execute on function public.lookup_customer_order(text,text) to anon, authenticated;

create or replace function public.confirm_cash_payment(p_order_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_order public.orders%rowtype; v_role text;
begin
  select role into v_role from public.profiles where id=(select auth.uid());
  if coalesce(v_role,'') not in ('admin','cashier') then raise exception 'Hanya admin atau kasir yang dapat mengonfirmasi pembayaran'; end if;
  select * into v_order from public.orders where id=p_order_id for update;
  if not found then raise exception 'Pesanan tidak ditemukan'; end if;
  if v_order.payment_method is distinct from 'cash' then raise exception 'Konfirmasi manual hanya untuk pembayaran tunai'; end if;
  if v_order.payment_status='paid' then raise exception 'Pembayaran sudah dikonfirmasi'; end if;
  if v_order.order_status='cancelled' then raise exception 'Pesanan dibatalkan'; end if;
  perform set_config('app.payment_confirmation','cash_confirm',true);
  update public.orders set payment_status='paid',paid_at=now(),paid_by=(select auth.uid()) where id=p_order_id;
  perform set_config('app.payment_confirmation','',true);
  return jsonb_build_object('success',true,'order_number',v_order.order_number);
end $$;
revoke all on function public.confirm_cash_payment(bigint) from public;
grant execute on function public.confirm_cash_payment(bigint) to authenticated;

create or replace function public.kitchen_update_order(p_order_id bigint,p_status text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_role text; v_order public.orders%rowtype;
begin
  select role into v_role from public.profiles where id=(select auth.uid());
  if coalesce(v_role,'') <> 'kitchen' then raise exception 'Hanya petugas dapur yang dapat memperbarui proses pesanan'; end if;
  if p_status not in ('preparing','ready') then raise exception 'Status dapur tidak valid'; end if;
  select * into v_order from public.orders where id=p_order_id for update;
  if not found then raise exception 'Pesanan tidak ditemukan'; end if;
  if v_order.order_status in ('completed','cancelled') then raise exception 'Pesanan sudah ditutup'; end if;
  if p_status='preparing' then
    if v_order.order_status not in ('pending','confirmed') then raise exception 'Status pesanan tidak dapat diubah'; end if;
    update public.orders set order_status='preparing' where id=p_order_id;
  else
    if v_order.order_status <> 'preparing' then raise exception 'Mulai proses pesanan terlebih dahulu'; end if;
    insert into public.order_status_histories(order_id,user_id,type,old_value,new_value)
      values(p_order_id,(select auth.uid()),'status','preparing','ready');
    update public.orders set order_status='completed',ready_at=now() where id=p_order_id;
  end if;
  return jsonb_build_object('success',true,'order_status',case when p_status='ready' then 'completed' else 'preparing' end);
end $$;
revoke all on function public.kitchen_update_order(bigint,text) from public;
grant execute on function public.kitchen_update_order(bigint,text) to authenticated;

create or replace function public.guard_order_updates()
returns trigger language plpgsql set search_path=public as $$
declare
  v_role text;
  v_payment_context text:=coalesce(current_setting('app.payment_confirmation',true),'');
  v_create_context text:=coalesce(current_setting('app.order_creation',true),'');
begin
  if new.payment_method is distinct from old.payment_method and v_create_context <> 'create' then
    raise exception 'Metode pembayaran tidak dapat diubah setelah pesanan dibuat';
  end if;
  if (new.paid_at is distinct from old.paid_at or new.paid_by is distinct from old.paid_by or new.payment_status is distinct from old.payment_status)
     and v_payment_context <> 'cash_confirm' and v_create_context <> 'create' then
    raise exception 'Status pembayaran hanya dapat diubah melalui proses konfirmasi resmi';
  end if;
  if new.order_status is distinct from old.order_status then
    select role into v_role from public.profiles where id=(select auth.uid());
    if v_role='kitchen' then
      if old.order_status in ('pending','confirmed') and new.order_status <> 'preparing' then
        raise exception 'Pesanan baru harus dimulai ke status sedang dibuat';
      elsif old.order_status='preparing' and new.order_status <> 'completed' then
        raise exception 'Pesanan yang diproses hanya dapat diselesaikan melalui tombol Siap Disajikan';
      elsif old.order_status not in ('pending','confirmed','preparing') then
        raise exception 'Pesanan sudah ditutup';
      end if;
    elsif v_role in ('admin','cashier') then
      if new.order_status <> 'cancelled' or old.order_status in ('completed','cancelled') then
        raise exception 'Admin dan kasir hanya dapat membatalkan pesanan aktif';
      end if;
    else
      raise exception 'Tidak memiliki izin mengubah pesanan';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists trg_guard_order_updates on public.orders;
create trigger trg_guard_order_updates before update on public.orders
for each row execute function public.guard_order_updates();

create or replace function public.log_order_updates()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.order_status is distinct from old.order_status then
    insert into public.order_status_histories(order_id,user_id,type,old_value,new_value)
      values(new.id,(select auth.uid()),'status',old.order_status,new.order_status);
  end if;
  if new.payment_status is distinct from old.payment_status then
    insert into public.order_status_histories(order_id,user_id,type,old_value,new_value)
      values(new.id,(select auth.uid()),'payment',old.payment_status,new.payment_status);
  end if;
  return new;
end $$;
drop trigger if exists trg_log_order_updates on public.orders;
create trigger trg_log_order_updates after update on public.orders
for each row execute function public.log_order_updates();

create or replace function public.open_cashier_shift(p_opening_cash numeric)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_role text; v_shift public.cashier_shifts%rowtype;
begin
  select role into v_role from public.profiles where id=(select auth.uid());
  if coalesce(v_role,'') not in ('admin','cashier') then raise exception 'Hanya admin atau kasir yang dapat membuka shift'; end if;
  if p_opening_cash is null or p_opening_cash<0 then raise exception 'Modal awal tidak valid'; end if;
  if exists(select 1 from public.cashier_shifts where cashier_id=(select auth.uid()) and status='open') then raise exception 'Masih ada shift yang belum ditutup'; end if;
  insert into public.cashier_shifts(cashier_id,opening_cash) values((select auth.uid()),p_opening_cash)
    returning * into v_shift;
  return jsonb_build_object('id',v_shift.id,'opening_cash',v_shift.opening_cash,'opened_at',v_shift.opened_at,'status',v_shift.status);
end $$;
revoke all on function public.open_cashier_shift(numeric) from public;
grant execute on function public.open_cashier_shift(numeric) to authenticated;

create or replace function public.close_cashier_shift(p_closing_cash numeric)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_shift public.cashier_shifts%rowtype; v_expected numeric(12,2);
begin
  if p_closing_cash is null or p_closing_cash<0 then raise exception 'Jumlah uang fisik tidak valid'; end if;
  select * into v_shift from public.cashier_shifts
    where cashier_id=(select auth.uid()) and status='open'
    order by opened_at desc limit 1 for update;
  if not found then raise exception 'Tidak ada shift aktif'; end if;
  select v_shift.opening_cash+coalesce(sum(grand_total),0) into v_expected
    from public.orders where payment_status='paid' and payment_method='cash'
      and paid_by=(select auth.uid()) and paid_at>=v_shift.opened_at;
  update public.cashier_shifts set closing_cash=p_closing_cash,expected_cash=v_expected,
    cash_difference=p_closing_cash-v_expected,status='closed',closed_at=now()
    where id=v_shift.id returning * into v_shift;
  return jsonb_build_object('id',v_shift.id,'opening_cash',v_shift.opening_cash,
    'closing_cash',v_shift.closing_cash,'expected_cash',v_shift.expected_cash,
    'cash_difference',v_shift.cash_difference,'opened_at',v_shift.opened_at,
    'closed_at',v_shift.closed_at,'status',v_shift.status);
end $$;
revoke all on function public.close_cashier_shift(numeric) from public;
grant execute on function public.close_cashier_shift(numeric) to authenticated;

